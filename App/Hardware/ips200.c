static void writeByte(uint8 data)
{
    /* 单字节帧仅占两个 TX FIFO 条目，不会堆积接收数据。
     * LAST=1 使帧结束后返回 wait；屏幕片选仍由 GPIO 独立保持。
     */
    IfxQspi_writeBasicConfigurationEndStream(&MODULE_QSPI2, spiBacon);
    IfxQspi_writeTransmitFifo(&MODULE_QSPI2, data);
    while (IfxQspi_getReceiveFifoLevel(&MODULE_QSPI2) == 0U) {}
    (void)IfxQspi_readReceiveFifo(&MODULE_QSPI2);
    while (IfxQspi_getPhase(&MODULE_QSPI2) != IfxQspi_Phase_wait) {}
}

static void writeCommand(uint8 command)
{
    IfxPort_setPinLow(&MODULE_P15, IPS200_DC_PIN);
    writeByte(command);
    IfxPort_setPinHigh(&MODULE_P15, IPS200_DC_PIN);
}

static void writeWord(uint16 data)
{
    writeByte((uint8)(data >> 8));
    writeByte((uint8)data);
}

/* 开始一个连续像素窗口，调用方在发送完像素后释放 CS。 */
static void beginWindow(uint16 x, uint16 y, uint16 width, uint16 height)
{
    IfxPort_setPinLow(&MODULE_P15, IPS200_CS_PIN);
    writeCommand(0x2A);
    writeWord(x);
    writeWord(x + width - 1U);
    writeCommand(0x2B);
    writeWord(y);
    writeWord(y + height - 1U);
    writeCommand(0x2C);
}

